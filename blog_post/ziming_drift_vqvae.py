import torch
import matplotlib.pyplot as plt
import torch.nn as nn

seed = 0
torch.manual_seed(seed)

# define dataset
amb_dim = 2
D = 1
class_per_dim = 2

bot_dim = 2

# generate data
def generate_data(n_samples, sigma=0.2):
    data = torch.zeros(n_samples, amb_dim)
    data_indices = torch.zeros(n_samples, D, dtype=torch.long)
    for i in range(D):
        data_indices[:, i] = torch.randint(0, class_per_dim, (n_samples,))
    data[:, :D] = data_indices[:, :D].float() / (class_per_dim - 1) - 1/2
    data = data + (torch.rand(n_samples, amb_dim) - 0.5) * sigma / (class_per_dim - 1)
    return data, data_indices

batch = 1000
data, _ = generate_data(batch)
#plt.scatter(data[:, 0], data[:, 1])

encoder = nn.Linear(amb_dim, bot_dim)
decoder = nn.Linear(bot_dim, amb_dim)

n_codes = 2

codes = torch.nn.Parameter(torch.rand(n_codes, bot_dim) - 0.5)

optimizer = torch.optim.Adam(list(encoder.parameters()) + list(decoder.parameters()) + [codes], lr=3e-3)

gamma = 1.0
beta = 0.25

# Collect training dynamics every save_every epochs for video
save_every = 10
hidden_history = []
codes_history = []
code_id_history = []

for i in range(1000):

    optimizer.zero_grad()

    hidden = encoder(data)  # (batch, bot_dim)

    dist = torch.norm(hidden[:, None, :] - codes[None, :, :], dim=-1)  # (batch, n_codes)
    code_id = torch.argmin(dist, dim=-1)  # (batch,)

    e = codes[code_id]  # (batch, bot_dim)

    recon = decoder(e)

    recon_loss = torch.mean((recon - data)**2)
    code_loss = torch.mean((hidden.detach() - e)**2)
    commit_loss = torch.mean((hidden - e.detach())**2)

    loss = gamma *recon_loss + code_loss + beta * commit_loss

    loss.backward()
    optimizer.step()

    if i % save_every == 0:
        with torch.no_grad():
            hidden_history.append(encoder(data).clone())
            codes_history.append(codes.data.clone())
            dist = torch.norm(hidden_history[-1][:, None, :] - codes_history[-1][None, :, :], dim=-1)
            code_id_history.append(torch.argmin(dist, dim=-1))

    if i % 100 == 0:
        print(f"Epoch {i}, Loss: {loss.item(), recon_loss.item(), code_loss.item(), commit_loss.item()}")

# Build video of training dynamics in hidden space
from matplotlib.animation import FuncAnimation, FFMpegWriter, PillowWriter
import numpy as np

# Global axis limits from all frames
all_hidden = torch.cat(hidden_history, dim=0)
all_codes = torch.cat(codes_history, dim=0)
