x_max = max(all_hidden[:, 0].max().item(), all_codes[:, 0].max().item())
y_min = min(all_hidden[:, 1].min().item(), all_codes[:, 1].min().item())
y_max = max(all_hidden[:, 1].max().item(), all_codes[:, 1].max().item())
margin = 0.1
x_min -= margin; x_max += margin; y_min -= margin; y_max += margin

fig, ax = plt.subplots(figsize=(6, 6))
n_frames = len(hidden_history)

